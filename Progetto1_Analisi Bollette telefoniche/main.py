def ottieniDatiTelefonate(nomeFile):
  telefonate = []
  chiamante = ()
  destinatario = ()
  cella_chiamante = ()
  cella_destinatario = ()
  minuti_conversazione = ()

  with open (nomeFile, 'r') as file:
    next(file)

    for line in file:
      line = line.strip('\n')
      line = line.split(';')

      if line[0].startswith('#'): # se iniziano con # non li considero
        continue

      chiamante = int(line[0])
      destinatario = int(line[1])
      cella_chiamante = int(line[2])
      cella_destinatario = int(line[3])

      inizio = line[4].split(':') # qui ricavo in un unico numero intero successivamente l'orario di inizio e sotto quello di fine
      fine = line[5].split(':')

      ggi = int(inizio[0]) # converto in intero
      hhi = int(inizio[1])
      mmi = int(inizio[2])
      minuti_inizio = (ggi*1440+hhi*60+mmi) # converto tutto in minuti in modo poi da fare una sottrazione tra fine ed inzio

      ggf = int(fine[0])
      hhf = int(fine[1])
      mmf = int(fine[2])
      minuti_fine = (ggf*1440+hhf*60+mmf)

      if not (1 <= ggi <= 31 and 0 <= hhi <= 23 and 0 <= mmi <= 59):
        continue

      if not (1 <= ggf <= 31 and 0 <= hhf <= 23 and 0 <= mmf <= 59):
        continue

      minuti_conversazione = int(minuti_fine - minuti_inizio + 1)

# Escludo tutti i possibili errori
      if (minuti_conversazione <= 0):
        continue

      if (chiamante == destinatario):
        continue

      if(minuti_inizio > minuti_fine):
        continue

      if(minuti_conversazione > 600):
        continue

# creo una tupla con dentro tutti i dati richiesti e poi appendo la tupla alla mia lista create
# cosi da avere un insieme di tuple dentro la lista come richiesto
      telefonata = (chiamante, destinatario, cella_chiamante, cella_destinatario, minuti_conversazione)
      telefonate.append((telefonata))


  return(telefonate)
telefonate = ottieniDatiTelefonate('telefonate.csv')
print(telefonate)

def calcolaBollette(datiChiamate):
  pagamento = {}

  for chiamata in datiChiamate:
    cliente = chiamata[0]
    minuti = chiamata[4]

    if (cliente not in pagamento):
      pagamento[cliente] = minuti
    else:
      pagamento[cliente] = pagamento[cliente] + minuti

  for customer in pagamento:
    if(pagamento[customer] > 20):
      pagamento[customer] = round((pagamento[customer] - 20) * 0.10, 2)
    else:
      pagamento[customer] = 0

  return(pagamento)

risultato = calcolaBollette(telefonate)

print(risultato)

