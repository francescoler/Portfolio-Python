biblioteca = {
    "Il Signore degli Anelli": 5,
    "Harry Potter": 8,
    "Pinocchio": 3,
    "Il Piccolo Principe": 6,
    "1984": 4,
    "Divina Commedia": 7
}


def aggiungi_libro(titolo, q_copie):
    if q_copie < 0:
        print("Errore, il numero di copie non può essere negativo")
    else:
        if titolo not in biblioteca:
            biblioteca[titolo] = q_copie
        else:
            biblioteca[titolo] = biblioteca[titolo] + q_copie

        print(biblioteca)


def rimuovi_libro(titolo):
    if titolo not in biblioteca:
        print("Errore, non è presente nessun libro con questo titolo a catalogo!")
    else:
        biblioteca.pop(titolo)
        print("Libro rimosso correttamente")
        print(biblioteca)


def verifica_disponibilita(titolo):
    if titolo not in biblioteca:
        return False
    else:
        if biblioteca[titolo] < 1:
            return False
        else:
            return True


def prendi_in_prestito(titolo):
    if titolo not in biblioteca:
        print("Il libro non è disponibile")
    else:
        if biblioteca[titolo] < 1:
            print("Spiacenti, al momento non abbiamo copie disponibili")
        else:
            biblioteca[titolo] = biblioteca[titolo] - 1

    print(biblioteca)


def statistiche_biblioteca():
    diz_biblio = {}

    totale_libri = len(biblioteca)
    somma = 0

    for copie in biblioteca.values():
        somma = somma + copie

    if totale_libri > 0:
        media = round(somma / totale_libri, 2)
    else:
        media = 0

    diz_biblio['totale_libri'] = totale_libri
    diz_biblio['copie_totali'] = somma
    diz_biblio['media_copie'] = media

    return diz_biblio


def visualizza_libri():
    if biblioteca == {}:
        print("La biblioteca è vuota")
    else:
        print(biblioteca)


def restaurare_libro(titolo, copie):
    if titolo not in biblioteca:
        print("Errore: il libro non è presente in archivio!")
    else:
        if copie <= 0:
            print("Errore: il numero di copie deve essere positivo")
        else:
            biblioteca[titolo] = biblioteca[titolo] + copie



while True:
    print('----- BENVENUTO IN BIBLIOTECA -----')
    print('')
    print('Scegli uno tra i seguenti comandi')
    print('')
    print('1 - Aggiungi un libro')
    print('2 - Rimuovi un libro')
    print('3 - Verifica un libro')
    print('4 - Prestito di un libro')
    print('5 - Statistiche')
    print('6 - Visualizza biblioteca')
    print('7 - Restaura un libro')
    print('8 - Esci')

    comando = input('Inserisci il comando che vuoi utilizzare: ')

    if comando == '1':
        libro = input('Inserisci il titolo del libro che vuoi aggiungere: ')
        try:
            copie = int(input("Inserisci il numero di copie: "))
            aggiungi_libro(libro, copie)
        except ValueError:
            print("Errore: inserisci un numero intero")

    elif comando == '2':
        libro = input('Inserisci il titolo del libro che vuoi eliminare: ')
        rimuovi_libro(libro)

    elif comando == '3':
        libro = input('Inserisci il nome del libro che vuoi cercare: ')
        risultato = verifica_disponibilita(libro)
        print(risultato)

    elif comando == '4':
        libro = input('Inserisci il nome del libro che vuoi prendere in prestito: ')
        prendi_in_prestito(libro)

    elif comando == '5':
        diz_biblio = statistiche_biblioteca()
        print(diz_biblio)

    elif comando == '6':
        visualizza_libri()

    elif comando == '7':
        libro = input('Inserisci il titolo del libro che cerchi: ')
        try:
            copie = int(input('Inserisci il numero di copie: '))
            restaurare_libro(libro, copie)
        except ValueError:
            print('Errore: inserisci un numero intero positivo')

    elif comando == '8':
        print('Grazie e arrivederci :)')
        break

    else:
        print("Comando non valido, riprova")
